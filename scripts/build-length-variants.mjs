import {readFile, writeFile, mkdir, access} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=dirname(dirname(fileURLToPath(import.meta.url)));
const main=await readFile(join(root,'main.tex'),'utf8');
const bib=await readFile(join(root,'references.bib'),'utf8');
const bibKeys=new Set([...bib.matchAll(/@\w+\{([^,]+),/g)].map(m=>m[1]));
await mkdir(join(root,'output'),{recursive:true});
await mkdir(join(root,'output','pdf'),{recursive:true});
for(const pages of [8,12]) {
 let source=main;
 for(const m of main.matchAll(/\\input\{sections\/([^}]+)\}/g)) {
  let path=join(root,'sections',m[1]+'.tex');
  if(pages===8) { const candidate=join(root,'variants/8-page',m[1]+'.tex'); try{await access(candidate);path=candidate;}catch{} }
  const section=(await readFile(path,'utf8')).replace(/^% !TeX root.*\n/,'');
  source=source.replace(m[0],()=>section);
 }
 source='% Complete '+pages+'-page working manuscript; generated by scripts/build-length-variants.mjs.\n% IEEE working format; target-venue compliance requires the conference handoff.\n'+source;
 const cites=new Set([...source.matchAll(/\\cite\{([^}]+)\}/g)].flatMap(m=>m[1].split(',')));
 for(const key of cites)if(!bibKeys.has(key))throw new Error('Unknown citation '+key);
 if(cites.size!==25)throw new Error('Expected25references; found '+cites.size);
 const name='archsync-'+pages+'page';
 await writeFile(join(root,name+'.tex'),source);
 if(!process.argv.includes('--source-only')) {
  const build=spawnSync(process.env.TECTONIC ?? 'tectonic',['--keep-logs','--keep-intermediates','--outdir','output',name+'.tex'],{cwd:root,encoding:'utf8'});
  await writeFile(join(root,'output',name+'-build.txt'),(build.stdout??'')+(build.stderr??'')); console.log(name+' build exit '+build.status);
  if(build.status!==0)process.exit(build.status??1);
  const log=await readFile(join(root,'output',name+'.log'),'utf8');
  if(/There were undefined|Citation .* undefined|Reference .* undefined/.test(log))throw new Error(name+' has unresolved references');
  await writeFile(join(root,name+'.pdf'),await readFile(join(root,'output',name+'.pdf')));
  await writeFile(join(root,'output','pdf',name+'.pdf'),await readFile(join(root,name+'.pdf')));
 }
 console.log('Generated '+name+'.tex');
}
